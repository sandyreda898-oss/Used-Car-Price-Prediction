"""
utils/pdf.py
Generates a premium branded PDF valuation report using ReportLab.
"""

import io
import requests
from datetime import datetime

from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.lib.colors import HexColor
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
)
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.enums import TA_CENTER

GOLD = HexColor("#D4AF37")
BLACK = HexColor("#0a0a0a")
CARD = HexColor("#161616")


def _fetch_image(url: str):
    try:
        resp = requests.get(url, timeout=8)
        resp.raise_for_status()
        return io.BytesIO(resp.content)
    except Exception:
        return None


def generate_pdf_report(details: dict, predicted_price: str, rating: str,
                         verdict: str, image_url: str = None) -> io.BytesIO:
    """
    details: dict of vehicle fields to display in the table
    predicted_price: formatted string e.g. "$26,800"
    rating: e.g. "★★★★☆"
    verdict: "Great Deal" / "Fair Price" / "Overpriced"
    image_url: optional car photo URL (Pexels)
    """
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(
        buffer, pagesize=A4,
        topMargin=20 * mm, bottomMargin=20 * mm,
        leftMargin=20 * mm, rightMargin=20 * mm,
    )

    styles = getSampleStyleSheet()
    title_style = ParagraphStyle(
        "LuxTitle", parent=styles["Title"], textColor=GOLD,
        fontSize=24, alignment=TA_CENTER, spaceAfter=4,
    )
    sub_style = ParagraphStyle(
        "LuxSub", parent=styles["Normal"], textColor=HexColor("#888888"),
        fontSize=10, alignment=TA_CENTER, spaceAfter=18,
    )
    section_style = ParagraphStyle(
        "Section", parent=styles["Heading2"], textColor=GOLD, fontSize=14, spaceBefore=14, spaceAfter=8,
    )
    price_style = ParagraphStyle(
        "Price", parent=styles["Title"], textColor=GOLD, fontSize=30, alignment=TA_CENTER, spaceAfter=4,
    )
    normal = styles["Normal"]

    story = []
    story.append(Paragraph("LUXECAR PREDICT", title_style))
    story.append(Paragraph("AI Powered Premium Vehicle Valuation Report", sub_style))
    story.append(Paragraph(f"Generated on {datetime.now().strftime('%Y-%m-%d %H:%M')}", sub_style))

    if image_url:
        img_data = _fetch_image(image_url)
        if img_data:
            img = Image(img_data, width=160 * mm, height=90 * mm)
            story.append(img)
            story.append(Spacer(1, 14))

    story.append(Paragraph("Estimated Price", section_style))
    story.append(Paragraph(predicted_price, price_style))
    story.append(Paragraph(f"Rating: {rating}  |  Verdict: {verdict}", sub_style))

    story.append(Paragraph("Vehicle Details", section_style))
    table_data = [["Field", "Value"]] + [[k, str(v)] for k, v in details.items()]
    table = Table(table_data, colWidths=[70 * mm, 90 * mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), GOLD),
        ("TEXTCOLOR", (0, 0), (-1, 0), BLACK),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 10),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [HexColor("#f5f5f0"), HexColor("#ffffff")]),
        ("GRID", (0, 0), (-1, -1), 0.5, HexColor("#dddddd")),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    story.append(table)

    story.append(Spacer(1, 20))
    story.append(Paragraph(
        "This report is generated by an AI valuation model and is intended for "
        "informational purposes only. Actual market prices may vary.",
        sub_style
    ))

    doc.build(story)
    buffer.seek(0)
    return buffer
